// Generates lib/data/skincare-brands.ts — the medical-grade skincare lines the
// practice actually stocks, grouped by brand, from the public Shopify catalogue
// at store.encompassspa.com. No API key needed.
//
// Why this exists rather than reading lib/data/shop.ts: that file is a SNAPSHOT
// that keeps only the first 4 products of each collection (skin-care declares
// count: 55 and lists 4). Reading it as the catalogue is how a review of this
// very page concluded the practice had "dropped SkinCeuticals and Obagi" —
// 28 SkinCeuticals and 10 Obagi products were live the whole time. Go to the
// collection endpoint, and page it: one request returns at most 250.
//
//   node scripts/sync-skincare-brands.mjs
//
// Re-run when the store's skin-care collection changes. Do not hand-edit the
// generated file.
import { writeFileSync } from 'node:fs'

const STORE = 'https://store.encompassspa.com'
const COLLECTION = 'skin-care'

// Brand order on the page. Brands present in the collection but absent here are
// still emitted, after these, so a new line cannot silently vanish.
const BRAND_ORDER = ['Skinceuticals', 'Obagi', 'SkinBetter Science', 'Hydrinity']

// Display names, where the vendor string is not how the brand writes itself.
const BRAND_LABEL = { Skinceuticals: 'SkinCeuticals' }

// Store clicks arrive in Shopify as Direct unless they are tagged — see
// lib/shop-links.ts for the full reasoning.
const utm = (url, campaign) =>
  `${url}${url.includes('?') ? '&' : '?'}utm_source=website&utm_medium=skincare-page&utm_campaign=${campaign}`

async function fetchAll() {
  const out = []
  for (let page = 1; page <= 10; page++) {
    const r = await fetch(`${STORE}/collections/${COLLECTION}/products.json?limit=250&page=${page}`)
    if (!r.ok) throw new Error(`${r.status} on page ${page}`)
    const { products } = await r.json()
    if (!products?.length) break
    out.push(...products)
  }
  if (!out.length) throw new Error('no products returned — refusing to write an empty file')
  return out
}

const products = await fetchAll()

const byBrand = new Map()
for (const p of products) {
  const v = p.vendor || 'Other'
  if (!byBrand.has(v)) byBrand.set(v, [])
  const variant = p.variants?.[0]
  byBrand.get(v).push({
    name: p.title,
    price: variant?.price ? `$${Number(variant.price).toFixed(2).replace(/\.00$/, '')}` : 'See store',
    href: utm(`${STORE}/products/${p.handle}`, v.toLowerCase().replace(/[^a-z0-9]+/g, '-')),
  })
}

const brands = [
  ...BRAND_ORDER.filter((b) => byBrand.has(b)),
  ...[...byBrand.keys()].filter((b) => !BRAND_ORDER.includes(b)).sort(),
]

const menus = brands.map((b) => ({
  heading: BRAND_LABEL[b] ?? b,
  items: byBrand.get(b).sort((x, y) => x.name.localeCompare(y.name)),
}))

const total = products.length
const body = `// GENERATED by scripts/sync-skincare-brands.mjs from the live Shopify catalogue
// at store.encompassspa.com/collections/${COLLECTION}. Do not edit by hand.
//
// ${total} products across ${brands.length} brands at the time of generation.
import type { PriceMenu } from '@/components/templates/ServicePageTemplate'

export const SKINCARE_BRAND_COUNT = ${brands.length}
export const SKINCARE_PRODUCT_COUNT = ${total}

export const SKINCARE_MENUS: PriceMenu[] = ${JSON.stringify(menus, null, 2)}
`

writeFileSync('lib/data/skincare-brands.ts', body)
console.log(`wrote lib/data/skincare-brands.ts — ${total} products, ${brands.length} brands`)
for (const m of menus) console.log(`  ${m.heading}: ${m.items.length}`)
